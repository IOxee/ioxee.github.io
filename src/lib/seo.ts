import { LANGUAGES, type Locale, localePath, localize } from './i18n';
import type { ExperienceEntry, Profile, Skill } from './schemas';

/** `og:locale` for each language: Open Graph uses `language_COUNTRY`, not the BCP 47 tags of `lang`. */
export const OG_LOCALES = {
	es: 'es_ES',
	ca: 'ca_ES',
	en: 'en_US',
} as const satisfies Record<Locale, string>;

export function alternateOgLocales(locale: Locale): string[] {
	return LANGUAGES.filter((language) => language.locale !== locale).map(
		(language) => OG_LOCALES[language.locale],
	);
}

/** The image seen when the link is shared. It is generated by `npm run assets:og`: 1200×630 is the Open Graph format. */
export const OG_IMAGE = {
	path: '/og.jpg',
	width: 1200,
	height: 630,
	type: 'image/jpeg',
} as const;

export function absoluteUrl(
	path: string,
	site: URL | string | undefined,
): string {
	if (!site) {
		throw new Error(
			'Falta `site` en astro.config.mjs: sin él no se pueden crear URLs absolutas',
		);
	}

	return new URL(path, site).href;
}

export interface LanguageAlternate {
	hreflang: string;
	href: string;
}

/**
 * The pages of all languages, plus `x-default` (the main language's, for those arriving with
 * another). Every page has to link to all of them, itself included: this way search engines
 * pair them up and show each person theirs.
 */
export function languageAlternates(
	site: URL | string | undefined,
): LanguageAlternate[] {
	const alternates = LANGUAGES.map(({ locale }) => ({
		hreflang: locale,
		href: absoluteUrl(localePath(locale), site),
	}));
	const main = alternates[0];

	return main
		? [...alternates, { hreflang: 'x-default', href: main.href }]
		: alternates;
}

export interface PersonSeo {
	name: string;
	jobTitle: string;
	url: string;
	image: string;
	sameAs: readonly string[];
	worksFor: readonly string[];
	knowsAbout: readonly string[];
}

/** Only what is used daily or with ease is declared as "knows about": the basics are not a trade. */
const KNOWN_SKILL_STATES: readonly Skill['state'][] = ['daily', 'comfortable'];

interface PersonSeoSource {
	profile: Profile;
	experience: readonly ExperienceEntry[];
	skills: readonly Skill[];
	locale: Locale;
	url: string;
	image: string;
}

export function personSeoFrom({
	profile,
	experience,
	skills,
	locale,
	url,
	image,
}: PersonSeoSource): PersonSeo {
	return {
		name: profile.name,
		jobTitle: localize(profile.headline, locale),
		url,
		image,
		sameAs: [profile.links.github, profile.links.linkedin],
		worksFor: experience.flatMap((entry) =>
			entry.kind === 'work' && entry.end === null && entry.organization
				? [entry.organization]
				: [],
		),
		knowsAbout: skills
			.filter((skill) => KNOWN_SKILL_STATES.includes(skill.state))
			.map((skill) => skill.name),
	};
}

/**
 * Structured data (schema.org): the site and the person, linked by `@id`. The site carries the
 * person's name so the search engine shows it instead of the domain. Of the person it includes only
 * what is already public on the page: no birth date or email, which crawlers
 * would pick up without anyone seeing them.
 */
export function siteJsonLd(person: PersonSeo, locale: Locale) {
	const personId = `${person.url}#person`;

	return {
		'@context': 'https://schema.org',
		'@graph': [
			{
				'@type': 'WebSite',
				name: person.name,
				url: person.url,
				inLanguage: locale,
				publisher: { '@id': personId },
			},
			{
				'@id': personId,
				'@type': 'Person',
				name: person.name,
				jobTitle: person.jobTitle,
				url: person.url,
				image: person.image,
				sameAs: [...person.sameAs],
				worksFor: person.worksFor.map((name) => ({
					'@type': 'Organization',
					name,
				})),
				knowsAbout: [...person.knowsAbout],
			},
		],
	};
}

/**
 * JSON ready to go inside `<script type="application/ld+json">`. `<`, `>` and `&` are escaped
 * (otherwise a text containing `</script>` would close the tag) and so are the U+2028/9 line separators.
 */
export function serializeJsonLd(data: object): string {
	return JSON.stringify(data)
		.replace(/</g, '\\u003c')
		.replace(/>/g, '\\u003e')
		.replace(/&/g, '\\u0026')
		.replace(/\u2028/g, '\\u2028')
		.replace(/\u2029/g, '\\u2029');
}
